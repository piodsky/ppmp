            $this->Ln(3);
        }
    }

    function Footer() {
        $this->SetY(-20);
        $this->SetFont('Arial', 'I', 8);
        $this->SetTextColor(128, 128, 128);
        $this->Cell(0, 5, 'Generated by PPMP Management System - Page ' . $this->PageNo() . ' of {nb}', 0, 0, 'C');
    }

    function NbLines($w, $txt) {
        $cw = &$this->CurrentFont['cw'];
        if($w==0)
            $w = $this->w - $this->rMargin - $this->x;
        $wmax = ($w-2*$this->cMargin)*1000/$this->FontSize;
        $s = str_replace("\r", '', $txt);
        $nb = strlen($s);
        if($nb>0 && $s[$nb-1]=="\n")
            $nb--;
        $sep = -1;
        $i = 0;
        $j = 0;
        $l = 0;
        $nl = 1;
        while($i<$nb) {
            $c = $s[$i];
            if($c=="\n") {
                $i++;
                $sep = -1;
                $j = $i;
                $l = 0;
                $nl++;
                continue;
            }
            if($c==' ')
                $sep = $i;
            $l += isset($cw[$c]) ? $cw[$c] : 0;
            if($l>$wmax) {
                if($sep==-1) {
                    if($i==$j)
                        $i++;
                } else
                    $i = $sep+1;
                $sep = -1;
                $j = $i;
                $l = 0;
                $nl++;
            } else
                $i++;
        }
        return $nl;
    }

    // Format department name with line breaks for better readability
    function formatDepartmentName($deptName) {
        $words = explode(' ', $deptName);
        $formatted = '';

        // Special handling for common department patterns
        if (count($words) >= 3) {
            // For "City Administrators Office" -> "City\nAdministrators\nOffice"
            if (strtolower($words[0]) === 'city' && strtolower($words[2]) === 'office') {
                return $words[0] . "\n" . $words[1] . "\n" . $words[2];
            }
            // For other 3+ word departments, put first word, then middle words, then last word
            elseif (count($words) == 3) {
                return $words[0] . "\n" . $words[1] . "\n" . $words[2];
            }
        }

        // Default: split into roughly equal parts
        $totalWords = count($words);
        if ($totalWords <= 2) {
            return implode("\n", $words);
        } elseif ($totalWords == 4) {
            return $words[0] . " " . $words[1] . "\n" . $words[2] . " " . $words[3];
        } else {
            // For longer names, group them
            $mid = ceil($totalWords / 2);
            $firstHalf = array_slice($words, 0, $mid);
            $secondHalf = array_slice($words, $mid);
            return implode(" ", $firstHalf) . "\n" . implode(" ", $secondHalf);
        }
    }

    // Table header for category report
    function TableHeader($departments) {
        // Add left margin for more space
        $this->SetX(15);

        $this->SetFont('Arial', 'B', 8);
        $this->SetFillColor(200, 200, 200);
        $this->SetTextColor(0, 0, 0);

        // Calculate available width for departments
        $pageWidth = 356; // Legal landscape width in mm
        $leftMargin = 15;
        $rightMargin = 10;
        $usableWidth = $pageWidth - $leftMargin - $rightMargin;
        $fixedWidth = 25 + 65 + 18 + 22 + 28 + 28; // Fixed columns width (adjusted)
        $availableWidth = $usableWidth - $fixedWidth;
        $deptWidth = max(12, $availableWidth / count($departments)); // Minimum 12mm per dept

        // Calculate max lines for department headers
        $maxDeptLines = 1;
        foreach($departments as $dept) {
            $formattedDept = $this->formatDepartmentName($dept);
            $lines = $this->NbLines($deptWidth, $formattedDept);
            $maxDeptLines = max($maxDeptLines, $lines);
        }
        $headerHeight = $maxDeptLines * 4; // Height per line for headers

        // Fixed columns
        $this->Cell(25, $headerHeight, 'Item Code', 1, 0, 'C', true);
        $this->Cell(65, $headerHeight, 'Item & Specifications', 1, 0, 'C', true);
        $this->Cell(18, $headerHeight, 'Unit', 1, 0, 'C', true);

        // Department columns
        foreach($departments as $dept) {
            $formattedDept = $this->formatDepartmentName($dept);
            $x = $this->GetX();
            $this->MultiCell($deptWidth, 4, $formattedDept, 1, 'C', true);
            $this->SetXY($x + $deptWidth, $this->GetY() - $headerHeight);
        }
        $this->Cell(22, $headerHeight, 'Total Qty', 1, 0, 'C', true);
        $this->Cell(28, $headerHeight, 'Unit Cost', 1, 0, 'C', true);
        $this->Cell(28, $headerHeight, 'Total Cost', 1, 1, 'C', true);
    }

    // Table row
    function TableRow($data, $departments) {
        // Add left margin for more space
        $this->SetX(15);

        $this->SetFont('Arial', '', 7);
        $this->SetTextColor(0, 0, 0);

        // Calculate department width dynamically (same as header)
        $pageWidth = 356; // Legal landscape width in mm
        $leftMargin = 15;
        $rightMargin = 10;
        $usableWidth = $pageWidth - $leftMargin - $rightMargin;
        $fixedWidth = 25 + 65 + 18 + 22 + 28 + 28; // Fixed columns width (adjusted)
        $availableWidth = $usableWidth - $fixedWidth;
        $deptWidth = max(12, $availableWidth / count($departments)); // Minimum 12mm per dept
        $widths = array_merge([25, 65, 18], array_fill(0, count($departments), $deptWidth), [22, 28, 28]);

        // Calculate max lines for the row
        $max_lines = 1;
        for($i = 0; $i < count($data); $i++) {
            $lines = $this->NbLines($widths[$i], $data[$i]);
            $max_lines = max($max_lines, $lines);
        }
        $height = $max_lines * 5;

        $startY = $this->GetY();
        for($i = 0; $i < count($data); $i++) {
            $x = $this->GetX();
            $align = ($i >= 3 && $i < 3 + count($departments)) ? 'C' : 'L';
            $this->MultiCell($widths[$i], 5, $data[$i], 1, $align);
            $this->SetXY($x + $widths[$i], $startY);
        }
        $this->Ln($height);
    }
}


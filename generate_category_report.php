// Extend FPDF class for Category Report
class CategoryPDF extends FPDF {
    public $currentYear;
    public $category;

    function __construct($orientation = 'L', $unit = 'mm', $size = 'Legal', $currentYear = null, $category = null) {
        $this->currentYear = $currentYear ?: date('Y');
        $this->category = $category ?: 'All Categories';
        parent::__construct($orientation, $unit, $size);
    }

